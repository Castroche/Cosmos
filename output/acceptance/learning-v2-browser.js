async page => {
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.setViewportSize({width:1600,height:1100});
  await page.request.put('http://127.0.0.1:8017/api/trading-intelligence/learning/settings',{data:{enabled:true,shadow_enabled:true,pinned_version:null}});
  await page.goto('http://127.0.0.1:8017');
  await page.getByRole('button',{name:'学习复盘',exact:true}).click();
  const panel = page.getByRole('region',{name:'交易学习',exact:true});
  await panel.getByText('有效交易经验',{exact:true}).waitFor();
  await panel.scrollIntoViewIfNeeded();
  await panel.screenshot({path:'output/acceptance/learning-v2-desktop.png'});
  const settings = await (await page.request.get('http://127.0.0.1:8017/api/trading-intelligence/learning/settings')).json();
  await panel.getByLabel('在线影子对照',{exact:true}).click();
  await page.waitForFunction(()=>{const e=document.querySelectorAll('.learning-controls input')[1]; return e && !e.checked && !e.disabled;});
  const disabled = await (await page.request.get('http://127.0.0.1:8017/api/trading-intelligence/learning/settings')).json();
  if(disabled.shadow_enabled) throw new Error('shadow switch did not persist');
  const versions = await (await page.request.get('http://127.0.0.1:8017/api/trading-intelligence/learning/versions')).json();
  await panel.locator('select').selectOption(versions.items[0].version);
  await page.waitForFunction(value=>document.querySelector('.learning-controls select').value===value && !document.querySelector('.learning-controls select').disabled,versions.items[0].version);
  const pinned = await (await page.request.get('http://127.0.0.1:8017/api/trading-intelligence/learning/settings')).json();
  if(pinned.pinned_version !== versions.items[0].version) throw new Error('pin failed');
  await panel.locator('select').selectOption('');
  await page.waitForFunction(()=>document.querySelector('.learning-controls select').value==='' && !document.querySelector('.learning-controls select').disabled);
  await page.setViewportSize({width:390,height:844});
  await panel.scrollIntoViewIfNeeded();
  await panel.screenshot({path:'output/acceptance/learning-v2-mobile.png'});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  if(overflow) throw new Error('mobile horizontal overflow');
  await page.route('**/api/trading-intelligence/learning/snapshot', route=>route.fulfill({json:{version:'empty',policy:'ADVISORY_ONLY',sample_count:0,skipped_count:0,groups:[],recent:[],records:[],excluded:[],updated_at:new Date().toISOString()}}));
  await panel.getByRole('button',{name:'刷新',exact:true}).click();
  await panel.getByText('等待完整成交证据；历史快照缺少时间证据时不会进入决策检索。',{exact:true}).waitFor();
  await panel.screenshot({path:'output/acceptance/learning-v2-empty.png'});
  await page.unroute('**/api/trading-intelligence/learning/snapshot');
  await page.route('**/api/trading-intelligence/learning/summary',route=>route.fulfill({status:503,json:{detail:'隔离验收故障'}}));
  await panel.getByRole('button',{name:'刷新',exact:true}).click();
  await panel.getByRole('alert').waitFor();
  const errorText = await panel.getByRole('alert').innerText();
  await panel.screenshot({path:'output/acceptance/learning-v2-error.png'});
  await page.unroute('**/api/trading-intelligence/learning/summary');
  await page.request.put('http://127.0.0.1:8017/api/trading-intelligence/learning/settings',{data:settings});
  await panel.getByRole('button',{name:'刷新',exact:true}).click();
  await panel.getByRole('alert').waitFor({state:'hidden'});
  return {desktop:'1600x1100',mobile:'390x844',overflow,errors,settingsPersisted:true,versionPin:true,emptyState:true,errorText,recovery:true,fixtureOnly:true};
}
